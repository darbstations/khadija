def build():
    wb = Workbook()
    wb.remove(wb.active)
    sheet_map(wb)
    for name in ROLES:
        sheet_role(wb, name)
    sheet_kpi(wb)
    wb.save(OUT)
    # فحصٌ ذاتيّ: لا مؤشر لمالكَين، ووزن كل مالكٍ ١٠٠٪
    names = [k[2] for k in KPI]
    dup = {n for n in names if names.count(n) > 1}
    bad = {r: round(sum(k[5] for k in KPI if k[0] == r), 4) for r in ROLES}
    print(f"✓ {OUT} · {len(wb.sheetnames)} ورقة")
    print(f"  مؤشرات: {len(KPI)} · مكرَّرة: {sorted(dup) or 'لا شيء'}")
    for r, s in bad.items():
        print(f"  {r:<22} {s:.0%} {'✓' if abs(s-1) < 1e-9 else '⛔'}")


if __name__ == "__main__":
    build()
