def mh(ws, row, c1, c2):
    """دمج خلايا الترويسة لتطابق دمج الجسم"""
    ws.merge_cells(start_row=row, start_column=c1, end_row=row, end_column=c2)
    for x in range(c1, c2 + 1):
        ws.cell(row, x).fill = W.FH
        ws.cell(row, x).border = W.BOX


