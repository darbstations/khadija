def priority(name):
    if any(k in name for k in _PRIO_LOW): return 1
    if any(k in name for k in _PRIO_HIGH): return 3
    return 2
def priority_label(p): return {3:"🔴 رئيسي", 2:"🟠 مهم", 1:"🟡 متابعة"}.get(p, "🟠 مهم")
def kpi_weights(records):
    """أوزان مطبّعة داخل الإدارة (مجموعها 1). تحترم الأوزان الصريحة إن وُجدت، وإلا فحسب الأولوية."""
    ov = globals().get("KPI_WEIGHT_OVERRIDE", {})
    raw = [ov.get(r[1], priority(r[1])) for r in records]   # r[1] = اسم المؤشر
    tot = sum(raw) or 1
    return [round(p/tot, 5) for p in raw]

